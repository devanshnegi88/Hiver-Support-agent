"""
Produces the "how well your judge agrees with a human" evidence the report
requires.

Workflow (manual, by design — this is you doing the human labeling):
  1. python eval/judge_calibration.py --step sample --n 35
     -> writes data/judge_calibration_sample.csv (a subset of golden set replies,
        generated by the agent, with columns for you to fill in by hand)
  2. Score each row yourself on the same 4 axes (1-5), BEFORE running step 3 —
     do not look at judge scores while human-labeling, or the comparison is
     meaningless.
  3. python eval/judge_calibration.py --step compare
     -> runs the judge on the same rows and prints agreement stats
"""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from config import GOLDEN_SET_CSV, DATA_DIR, BRAND_HANDLE  # noqa: E402
from pipeline import run_agent  # noqa: E402
from retrieval import PrecedentIndex  # noqa: E402
from llm_judge import judge_reply, human_agreement  # noqa: E402

CALIB_PATH = DATA_DIR / "judge_calibration_sample.csv"


def step_sample(n: int, seed: int = 7):
    golden = pd.read_csv(GOLDEN_SET_CSV)
    sample = golden.sample(n=min(n, len(golden)), random_state=seed)

    index = PrecedentIndex.load()
    rows = []
    for _, row in sample.iterrows():
        result = run_agent(row["customer_message"], index, brand=BRAND_HANDLE,
                            exclude_id=row["customer_tweet_id"])
        rows.append({
            "customer_message": row["customer_message"],
            "draft_reply": result.draft_reply,
            "human_grounded": "", "human_relevant": "", "human_tone": "", "human_actionable": "",
        })
    pd.DataFrame(rows).to_csv(CALIB_PATH, index=False)
    print(f"Wrote {len(rows)} rows to {CALIB_PATH}. Fill in the human_* columns (1-5) by hand.")


def step_compare(heuristic: bool = True):
    df = pd.read_csv(CALIB_PATH)
    for col in ["human_grounded", "human_relevant", "human_tone", "human_actionable"]:
        if df[col].isna().any() or (df[col] == "").any():
            raise ValueError(f"{col} has unfilled rows — finish human labeling first.")

    human_scores = [{
        "grounded": int(r.human_grounded),
        "relevant": int(r.human_relevant),
        "tone": int(r.human_tone),
        "actionable": int(r.human_actionable),
    } for r in df.itertuples()]

    judge_scores = [
        judge_reply(
            r.customer_message,
            r.draft_reply,
            "(calibration run)",
            heuristic=heuristic,
        )
        for r in df.itertuples()
    ]

    agreement = human_agreement(judge_scores, human_scores)
    table = pd.DataFrame(agreement).T
    print(table)
    out = Path(__file__).resolve().parent.parent / "results" / "judge_agreement.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "n": len(df),
        "heuristic_judge": heuristic,
        "agreement": agreement,
    }
    out.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--step", choices=["sample", "compare"], required=True)
    ap.add_argument("--n", type=int, default=35)
    ap.add_argument(
        "--heuristic-judge",
        action="store_true",
        help="Compare against the heuristic judge (15-minute path). Default for compare.",
    )
    ap.add_argument("--llm-judge", action="store_true")
    args = ap.parse_args()
    if args.step == "sample":
        step_sample(args.n)
    else:
        heuristic = not args.llm_judge
        step_compare(heuristic=heuristic)
